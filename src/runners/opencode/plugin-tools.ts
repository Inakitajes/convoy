/**
 * Convoy tool rendering for the OpenCode v2 plugin API (change
 * `runner-parity-opencode-v2`, task 4.5).
 *
 * V1 custom tools (`src/report-bridge.ts`, `src/advisor-bridge.ts`) registered a
 * bare default export that OpenCode derived a tool name from. V2 plugins are
 * `Plugin.define({ id, setup })` modules that register tools through
 * `ctx.tool.transform((editor) => editor.add({ name, description, input, execute }))`
 * (see `node_modules/@opencode/plugin` and the V2 plugin migration guide).
 *
 * This module only RENDERS module source as strings. It never touches the
 * filesystem: writing the per-run plugin directory is the adapter's job, so the
 * registration can be planned and inspected before any prompt is admitted.
 *
 * The bridge URL and bearer token are embedded as string literals inside the
 * `execute` function — the code path that actually calls the bridge — exactly as
 * the existing bridges do. They never appear in a comment, the plugin id, or the
 * tool description.
 */

import { join } from "node:path"

import { advisorFeedbackToolName, advisorToolName } from "../../advisor"
import { writeReportToolName } from "../../report"

/** One Convoy tool to expose to OpenCode through a v2 plugin module. */
export type PluginToolSpec = {
  name: string
  description: string
  bridgeUrl: string
  token: string
}

/** A planned per-run plugin directory: a base plus the module sources to write. */
export type PluginRegistration = {
  dir: string
  files: Record<string, string>
}

/** Registration health for the tools an attempt will rely on, checked before prompting. */
export type PluginToolHealth = { name: string; registered: boolean }

/** Escapes a value so it survives embedding in the renderer's template literal, then JSON-quotes it. */
function sourceLiteral(value: string): string {
  const escaped = value.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$/g, "\\$")
  return JSON.stringify(escaped)
}

/** A stable, filesystem-safe plugin id derived from the tool name. */
function pluginId(name: string): string {
  return `convoy-${name.replace(/[^a-zA-Z0-9._-]/g, "_")}`
}

/** A deterministic, filesystem-safe plugin file name derived from the tool name. */
function pluginFileName(name: string): string {
  return `${name.replace(/[^a-zA-Z0-9._-]/g, "_")}.ts`
}

/**
 * The module a rendered tool belongs to. The advisor plugin registers both
 * `advisor` and `advisor_feedback`, so feedback is owned by the advisor module
 * rather than a file of its own.
 */
function ownerToolName(toolName: string): string {
  return toolName === advisorFeedbackToolName ? advisorToolName : toolName
}

/** The plugin id that registers `toolName` in a rendered module. */
export function pluginIdForTool(toolName: string): string {
  return pluginId(ownerToolName(toolName))
}

/** The module file name that registers `toolName` in a planned directory. */
export function pluginFileNameForTool(toolName: string): string {
  return pluginFileName(ownerToolName(toolName))
}

/** Renders the `write_report` plugin: one tool that persists the phase report through Convoy. */
export function renderWriteReportPlugin(spec: PluginToolSpec): string {
  const urlLiteral = sourceLiteral(spec.bridgeUrl)
  const tokenLiteral = sourceLiteral(spec.token)
  return `// Generated by Convoy. Do not edit: it is rewritten on every run.
import { Plugin } from "@opencode/plugin"

export default Plugin.define({
  id: ${JSON.stringify(pluginId(spec.name))},
  async setup(ctx) {
    await ctx.tool.transform((editor) => {
      editor.add({
        name: ${JSON.stringify(spec.name)},
        description: ${JSON.stringify(spec.description)},
        input: {
          type: "object",
          properties: {
            markdown: { type: "string" },
            dimensions: {
              type: "object",
              properties: {
                prd: { type: "number" },
                tests: { type: "number" },
                security: { type: "number" },
                maintainability: { type: "number" },
                operational: { type: "number" },
                scope: { type: "number" },
              },
              additionalProperties: false,
            },
            mustFix: { type: "array", items: { type: "string" } },
            gaps: {
              type: "object",
              properties: {
                prd: { type: "string" },
                tests: { type: "string" },
                security: { type: "string" },
                maintainability: { type: "string" },
                operational: { type: "string" },
                scope: { type: "string" },
              },
              additionalProperties: false,
            },
            confidence: { type: "string", enum: ["high", "medium", "low"] },
            commit: {
              type: "object",
              properties: {
                subject: { type: "string" },
                details: { type: "array", items: { type: "string" } },
              },
              required: ["subject"],
              additionalProperties: false,
            },
          },
          required: ["markdown"],
          additionalProperties: false,
        },
        async execute(input, context) {
          const url = ${urlLiteral}
          const token = ${tokenLiteral}
          try {
            const response = await fetch(url, {
              method: "POST",
              headers: { "content-type": "application/json", authorization: "Bearer " + token },
              body: JSON.stringify({ sessionID: context.sessionID, payload: input }),
              signal: context.signal,
            })
            const body = await response.json().catch(() => ({}))
            if (!response.ok) throw new Error(typeof body?.error === "string" ? body.error : "report bridge returned " + response.status)
            return { content: typeof body?.message === "string" ? body.message : "Report saved." }
          } catch (error) {
            throw new Error(${JSON.stringify(spec.name)} + " failed: " + (error instanceof Error ? error.message : String(error)))
          }
        },
      })
    })
  },
})
`
}

/**
 * Renders the advisor plugin: the on-demand `advisor` tool plus the
 * `advisor_feedback` tool, mirroring the two tools `installAdvisorTool` writes.
 * Both POST to the same authenticated loopback bridge.
 */
export function renderAdvisorPlugin(spec: PluginToolSpec): string {
  const urlLiteral = sourceLiteral(spec.bridgeUrl)
  const tokenLiteral = sourceLiteral(spec.token)
  return `// Generated by Convoy. Do not edit: it is rewritten on every run.
import { Plugin } from "@opencode/plugin"

export default Plugin.define({
  id: ${JSON.stringify(pluginId(spec.name))},
  async setup(ctx) {
    await ctx.tool.transform((editor) => {
      editor.add({
        name: ${JSON.stringify(spec.name)},
        description: ${JSON.stringify(spec.description)},
        input: { type: "object", properties: {}, additionalProperties: false },
        async execute(_input, context) {
          const url = ${urlLiteral}
          const token = ${tokenLiteral}
          if (!url || !token) return { content: "No advice available: this session has no advisor configured. Continue on your own judgement." }
          try {
            const response = await fetch(url, {
              method: "POST",
              headers: { "content-type": "application/json", authorization: "Bearer " + token },
              body: JSON.stringify({ sessionID: context.sessionID }),
              signal: context.signal,
            })
            if (!response.ok) return { content: "No advice available (advisor bridge returned " + response.status + "). Continue on your own judgement." }
            const body = await response.json()
            return { content: typeof body?.advice === "string" && body.advice ? body.advice : "No advice available. Continue on your own judgement." }
          } catch (error) {
            return { content: "No advice available (" + (error instanceof Error ? error.message : String(error)) + "). Continue on your own judgement." }
          }
        },
      })
      editor.add({
        name: ${JSON.stringify(advisorFeedbackToolName)},
        description: "Record whether you adopted the latest advisor guidance. outcome must be adopted, partially-adopted, or rejected; note is optional and brief.",
        input: {
          type: "object",
          properties: {
            outcome: { type: "string", enum: ["adopted", "partially-adopted", "rejected"] },
            note: { type: "string" },
            callId: { type: "string" },
          },
          required: ["outcome"],
          additionalProperties: false,
        },
        async execute(input, context) {
          const base = ${urlLiteral}
          const token = ${tokenLiteral}
          if (!base || !token) return { content: "Advisor feedback unavailable for this session." }
          const args = input as { outcome?: string; note?: string; callId?: string }
          try {
            const url = new URL(base)
            url.pathname = "/feedback"
            const response = await fetch(url, {
              method: "POST",
              headers: { "content-type": "application/json", authorization: "Bearer " + token },
              body: JSON.stringify({ sessionID: context.sessionID, outcome: args?.outcome, note: args?.note, callId: args?.callId }),
              signal: context.signal,
            })
            if (!response.ok) return { content: "Advisor feedback was not recorded (bridge returned " + response.status + ")." }
            const body = await response.json()
            return { content: typeof body?.message === "string" ? body.message : "Advisor feedback recorded." }
          } catch (error) {
            return { content: "Advisor feedback was not recorded (" + (error instanceof Error ? error.message : String(error)) + ")." }
          }
        },
      })
    })
  },
})
`
}

/** Chooses the renderer for a spec: the report tool by name, the advisor plugin otherwise. */
function renderPlugin(spec: PluginToolSpec): string {
  return spec.name === writeReportToolName ? renderWriteReportPlugin(spec) : renderAdvisorPlugin(spec)
}

/**
 * Plans a per-run plugin directory. `baseDir` is the run root, so two runs get
 * different, isolated directories and never share a mutable tool shim. File
 * names are deterministic functions of the tool names, and duplicate names are a
 * planning error rather than a silent overwrite.
 */
export function planPluginRegistration(baseDir: string, specs: readonly PluginToolSpec[]): PluginRegistration {
  const dir = join(baseDir, "plugins")
  const files: Record<string, string> = {}
  for (const spec of specs) {
    const fileName = pluginFileName(spec.name)
    if (Object.prototype.hasOwnProperty.call(files, fileName)) {
      throw new Error(`duplicate plugin tool file name: ${fileName}`)
    }
    files[fileName] = renderPlugin(spec)
  }
  return { dir, files }
}

/**
 * Verifies every required tool actually registered. Used BEFORE a prompt is
 * admitted: an unregistered report/advisor tool would silently change what the
 * agent can do, so the caller must fail closed on `ok === false`.
 */
export function pluginHealth(descriptors: readonly PluginToolHealth[]): { ok: boolean; missing: string[] } {
  const missing = descriptors.filter((descriptor) => !descriptor.registered).map((descriptor) => descriptor.name)
  return { ok: missing.length === 0, missing }
}

/** The advisor tool names a rendered advisor plugin registers, in order. */
export const advisorPluginToolNames = [advisorToolName, advisorFeedbackToolName] as const

/**
 * Every tool name the given specs will actually register: a report spec
 * registers one tool, an advisor spec registers two. Used to build the
 * registration-health list that is checked before any prompt is admitted.
 */
export function requiredToolNames(specs: readonly PluginToolSpec[]): string[] {
  return specs.flatMap((spec) =>
    spec.name === writeReportToolName ? [spec.name] : [advisorToolName, advisorFeedbackToolName],
  )
}
